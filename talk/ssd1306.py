class SSD1306_I2C:
    def __init__(self, width, height, i2c, addr=0x3C):
        self.width = width
        self.height = height
        self.i2c = i2c
        self.addr = addr
        self.pages = height // 8
        self.buffer = bytearray(self.pages * width)
        self.framebuf = framebuf.FrameBuffer(
            self.buffer, width, height, framebuf.MONO_VLSB
        )
        self.fill = self.framebuf.fill
        self.text = self.framebuf.text
        self.pixel = self.framebuf.pixel
        self._temp = bytearray(2)
        self._init_display()

    def _cmd(self, value):
        self._temp[0] = 0x80
        self._temp[1] = value
        self.i2c.writeto(self.addr, self._temp)

    def _data(self):
        self.i2c.writeto(self.addr, b"\x40" + self.buffer)

    def _init_display(self):
        commands = (
            0xAE, 0x20, 0x00, 0x40, 0xA1, 0xC8,
            0x81, 0x7F, 0xA8, self.height - 1, 0xD3, 0x00,
            0xDA, 0x12 if self.height == 64 else 0x02,
            0xD5, 0x80, 0xD9, 0xF1,
            0xDB, 0x30, 0x8D, 0x14, 0xA4, 0xA6, 0xAF,
        )
        for command in commands:
            self._cmd(command)
        self.fill(0)
        self.show()

    def show(self):
        self._cmd(0x21)
        self._cmd(0)
        self._cmd(self.width - 1)
        self._cmd(0x22)
        self._cmd(0)
        self._cmd(self.pages - 1)
        self._data()

    def big_text(self, text, x, y, scale=2):
        for char in text.upper():
            glyph = FONT_5X7.get(char, FONT_5X7[" "])
            for col in range(5):
                bits = glyph[col]
                for row in range(7):
                    if bits & (1 << row):
                        for dx in range(scale):
                            for dy in range(scale):
                                px = x + col * scale + dx
                                py = y + row * scale + dy
                                if px < self.width and py < self.height:
                                    self.pixel(px, py, 1)
            x += 6 * scale
